#!/usr/bin/env node
/**
 * Extracts the CareerPilot AI project block from master-resume.md into a Deno-importable
 * module for Edge Functions. Run before deploy or via `npm run sync:corpus`.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');
const masterPath = path.join(root, 'src/content/career-corpus/master-resume.md');
const outPath = path.join(root, 'supabase/functions/_shared/career-corpus/careerpilot-section.generated.ts');

const NEEDLE = 'CareerPilot AI — Autonomous Job Search Platform';

function extractCareerPilotSection(master) {
  const lines = master.split('\n');
  const needleLower = NEEDLE.toLowerCase();
  let start = -1;

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    if (!line.startsWith('--- Project:')) continue;
    if (line.toLowerCase().includes(needleLower)) {
      start = i;
      break;
    }
  }
  if (start < 0) {
    throw new Error(`CareerPilot project block not found in ${masterPath}`);
  }

  let end = lines.length;
  for (let i = start + 1; i < lines.length; i++) {
    if (lines[i].startsWith('--- ') || lines[i].match(/^={10,}/)) {
      end = i;
      break;
    }
  }
  return lines.slice(start, end).join('\n').trim();
}

const master = fs.readFileSync(masterPath, 'utf8');
const section = extractCareerPilotSection(master);
const banner = `// Generated by scripts/sync-careerpilot-section.mjs — do not edit manually.\n`;
const body = `${banner}export const CAREERPILOT_PROJECT_SECTION_TEMPLATE = ${JSON.stringify(section)};\n`;
fs.writeFileSync(outPath, body, 'utf8');
console.log(`Wrote CareerPilot section (${section.length} chars) → ${path.relative(root, outPath)}`);
